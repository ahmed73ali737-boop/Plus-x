class Persistence:
    """Registry of the adapters installed by the composition root.

    Attribute annotations document each port; lookups fail loudly when the
    composition root has not installed an implementation.
    """

    transactions: Transactions
    sites: SiteRepository
    guests: GuestRepository
    presence: PresenceRepository
    checkins: CheckinLog
    admission: AdmissionRepository
    devices: DeviceRepository
    access: AccessRepository
    identity: IdentityRepository
    audit: AuditLog
    submissions: SubmissionRepository
    site_admin: SiteAdminRepository
    account_requests: AccountRequestRepository
    committee: CommitteeRepository
    certificates: CertificateRepository
    self_certificates: SelfCertificateRepository

    def __init__(self):
        self._adapters: dict[str, object] = {}

    def install(self, **adapters) -> None:
        self._adapters.update(adapters)

    def installed(self) -> bool:
        return bool(self._adapters)

    def __getattr__(self, name: str):
        adapters = self.__dict__.get('_adapters', {})
        if name in adapters:
            return adapters[name]
        raise RuntimeError('PERSISTENCE_NOT_CONFIGURED:' + name)


