"""Ports: the persistence interfaces the application layer depends on.

Use cases receive an opaque transaction handle (``tx``) owned by their caller
(the API layer opens it, or a background worker opens it through
``persistence.transactions``). They never touch SQL: every read and write goes
through one of the repository protocols below. The infrastructure layer
(app.infrastructure.persistence) provides SQLAlchemy Core implementations and
installs them into ``persistence`` at the composition root
(``make_engine``/``create_app``); tests may install in-memory fakes instead.
"""
from __future__ import annotations

from contextlib import AbstractContextManager
from typing import Any, Protocol

from app.domain.gate import GateTransition, GuestPresence

Tx = Any  # an open unit of work; opaque to the application layer
Row = dict


class Transactions(Protocol):
    def write(self, database) -> AbstractContextManager[Tx]: ...
    def read(self, database) -> AbstractContextManager[Tx]: ...
    def savepoint(self, tx: Tx) -> AbstractContextManager[None]: ...
    def is_transient_failure(self, error: BaseException) -> bool: ...
    def is_conflict(self, error: BaseException) -> bool: ...


